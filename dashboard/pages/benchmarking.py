"""
Benchmarking dashboard page — FedAvg vs FedProx comparison.

Displays accuracy curves, F1 scores, communication overhead, and training
time from benchmark_comparison.csv (generated by the benchmarking suite).
"""

from __future__ import annotations

import os
from pathlib import Path

import streamlit as st
import plotly.graph_objects as go
from plotly.subplots import make_subplots

RESULTS_DIR = Path(__file__).parents[2] / "data" / "results"
CSV_PATH = RESULTS_DIR / "benchmark_comparison.csv"


def render() -> None:
    st.header("Benchmarking: FedAvg vs FedProx")

    st.markdown(
        """
        Compare convergence speed, communication efficiency, and privacy cost
        between **FedAvg** and **FedProx** (proximal regularization).

        Run `python -m fedprivacylab.benchmarking.suite` to generate fresh results.
        """
    )

    col_run, col_status = st.columns([2, 3])
    with col_run:
        run_benchmark = st.button("Run Benchmark Now", type="primary")

    if run_benchmark:
        with st.spinner("Running FedAvg and FedProx benchmarks (this may take 1-2 min)..."):
            try:
                from fedprivacylab.benchmarking.suite import benchmark_comparison
                rounds = st.session_state.get("bench_rounds", 10)
                clients = st.session_state.get("bench_clients", 5)
                mu = st.session_state.get("bench_mu", 0.01)
                csv_path = benchmark_comparison(num_rounds=rounds, num_clients=clients, mu=mu)
                st.success(f"Benchmark complete! Results saved to {csv_path}")
            except Exception as e:
                st.error(f"Benchmark failed: {e}")

    with st.expander("Benchmark Configuration"):
        col1, col2, col3 = st.columns(3)
        with col1:
            st.session_state["bench_rounds"] = st.slider("Rounds", 5, 30, 10)
        with col2:
            st.session_state["bench_clients"] = st.slider("Clients", 2, 20, 5)
        with col3:
            st.session_state["bench_mu"] = st.select_slider("FedProx μ", [0.001, 0.01, 0.1, 0.5], value=0.01)

    if not CSV_PATH.exists():
        st.info("No benchmark data found. Click **Run Benchmark Now** to generate results.")
        return

    try:
        import pandas as pd
        df = pd.read_csv(CSV_PATH)
    except Exception as e:
        st.error(f"Failed to load benchmark CSV: {e}")
        return

    algorithms = df["algorithm"].unique().tolist()
    colors = {"FedAvg": "#636EFA", "FedProx": "#EF553B"}

    # ── KPI summary ─────────────────────────────────────────────────────────────
    st.subheader("Summary")
    kpi_cols = st.columns(len(algorithms) * 2)
    for i, algo in enumerate(algorithms):
        sub = df[df["algorithm"] == algo]
        kpi_cols[i * 2].metric(
            f"{algo} Final Accuracy",
            f"{sub['accuracy'].iloc[-1]:.3f}",
            delta=f"{sub['accuracy'].iloc[-1] - sub['accuracy'].iloc[0]:+.3f}",
        )
        kpi_cols[i * 2 + 1].metric(
            f"{algo} Total Time (s)",
            f"{sub['training_time_seconds'].sum():.1f}s",
        )

    # ── Charts ──────────────────────────────────────────────────────────────────
    st.subheader("Accuracy Curves")
    fig_acc = go.Figure()
    for algo in algorithms:
        sub = df[df["algorithm"] == algo]
        color = colors.get(algo.split("(")[0], "#00CC96")
        fig_acc.add_trace(go.Scatter(
            x=sub["round"], y=sub["accuracy"],
            name=algo, line=dict(color=color, width=2),
            mode="lines+markers",
        ))
    fig_acc.update_layout(
        xaxis_title="Round", yaxis_title="Accuracy",
        template="plotly_dark", height=350,
    )
    st.plotly_chart(fig_acc, use_container_width=True)

    col_left, col_right = st.columns(2)

    with col_left:
        st.subheader("Communication Overhead")
        fig_comm = go.Figure()
        for algo in algorithms:
            sub = df[df["algorithm"] == algo]
            color = colors.get(algo.split("(")[0], "#00CC96")
            fig_comm.add_trace(go.Scatter(
                x=sub["round"],
                y=(sub["bytes_transferred"].cumsum() / 1e6).tolist(),
                name=algo,
                line=dict(color=color),
            ))
        fig_comm.update_layout(
            xaxis_title="Round", yaxis_title="Cumulative MB",
            template="plotly_dark", height=300,
        )
        st.plotly_chart(fig_comm, use_container_width=True)

    with col_right:
        st.subheader("Training Time per Round")
        fig_time = go.Figure()
        for algo in algorithms:
            sub = df[df["algorithm"] == algo]
            color = colors.get(algo.split("(")[0], "#00CC96")
            fig_time.add_trace(go.Bar(
                x=sub["round"], y=sub["training_time_seconds"],
                name=algo, marker_color=color, opacity=0.8,
            ))
        fig_time.update_layout(
            barmode="group",
            xaxis_title="Round", yaxis_title="Seconds",
            template="plotly_dark", height=300,
        )
        st.plotly_chart(fig_time, use_container_width=True)

    st.subheader("Privacy Budget Consumption (ε)")
    fig_eps = go.Figure()
    for algo in algorithms:
        sub = df[df["algorithm"] == algo]
        color = colors.get(algo.split("(")[0], "#00CC96")
        fig_eps.add_trace(go.Scatter(
            x=sub["round"], y=sub["epsilon"],
            name=algo, line=dict(color=color, dash="dot"),
        ))
    fig_eps.update_layout(
        xaxis_title="Round", yaxis_title="Cumulative ε",
        template="plotly_dark", height=300,
    )
    st.plotly_chart(fig_eps, use_container_width=True)

    st.subheader("Raw Data")
    st.dataframe(df, use_container_width=True)


render()
